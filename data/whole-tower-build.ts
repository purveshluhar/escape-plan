// Builds the whole 432 Park tower from the package files in data/432-park/.
// Run: node data/whole-tower-build.ts
// 1. Gives every apartment floor a random typical plan (seed 432, the turn the package gave it).
// 2. Rewrites type_assignment in the package's Rooms CSV to the GLB room each room comes from
//    (the original CSV is kept as 432_Park_Avenue_Rooms.original.csv, which the script reads).
// 3. Rebuilds the tower part of data/building.json (levels, nodes and edges named T<nn>) from those
//    plans, plus the lifts and stairs that join the slice to the tower (sliceJoin), and writes
//    data/tower-floors.ts for the viewer. The slice's own rooms and edges are never touched.
// Rerunnable: the same seed gives the same tower. Owner: P5.
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import type { Building, Edge } from '../contract/types.ts';
import { CLEAR_HEIGHT, assignPlans, glbRoomName, planRooms } from './tower-plans.ts';
import type { TypicalPlan } from './tower-plans.ts';
import { buildTower, isGeneratedJoin, sliceJoin } from './whole-tower.ts';
import type { PackageMeta } from './whole-tower.ts';

const SEED = 432;
const PKG = new URL('./432-park/', import.meta.url);
const BUILDING = new URL('./building.json', import.meta.url);
const FLOORS_TS = new URL('./tower-floors.ts', import.meta.url);
const CSV = new URL('432_Park_Avenue_Rooms.csv', PKG);
const CSV_ORIGINAL = new URL('432_Park_Avenue_Rooms.original.csv', PKG);

const meta = JSON.parse(readFileSync(new URL('432_Park_Avenue_Metadata.json', PKG), 'utf8')) as { tower: PackageMeta };
const plans = JSON.parse(readFileSync(new URL('typical_plans.json', PKG), 'utf8')) as TypicalPlan[];
const building = JSON.parse(readFileSync(BUILDING, 'utf8')) as Building;

// ---- 1. a random plan per apartment floor
const floors = meta.tower.floors;
const assigned = assignPlans(floors, SEED);
const apartment = floors.filter((f) => !f.program);
const floorId = (level: string): string => apartment.find((f) => `T${String(f.level_index).padStart(2, '0')}` === level)!.floor_id;
const rooms = Object.entries(assigned).flatMap(([level, a]) => planRooms(floorId(level), a, plans));

// ---- 2. the CSV
const header = 'asset,room_id,floor_id,unit_id,room_type,model_area_m2,clear_height_m,estimated_volume_m3,layout_id,is_generated,type_assignment,area_status';
const cell = (v: string | number): string => (/[",\n]/.test(String(v)) ? `"${String(v).replace(/"/g, '""')}"` : String(v));
if (!existsSync(CSV_ORIGINAL)) copyFileSync(CSV, CSV_ORIGINAL);
const apartmentFloorIds = new Set(rooms.map((r) => r.floor_id));
const original = readFileSync(CSV_ORIGINAL, 'utf8').trimEnd().split('\n').slice(1);
const lines: string[] = [header];
const done = new Set<string>();
for (const line of original) {
  const [asset, , floor] = line.split(',');
  if (asset !== 'tower' || !apartmentFloorIds.has(floor!)) {
    lines.push(line);
    continue;
  }
  if (done.has(floor!)) continue; // the floor's rows were replaced where its first row was
  done.add(floor!);
  rooms.filter((r) => r.floor_id === floor).forEach((r, i) => {
    lines.push([
      'tower', `${floor}_R${String(i + 1).padStart(3, '0')}`, floor!, r.unit_id, r.room_type, r.model_area_m2!,
      CLEAR_HEIGHT, Math.round(r.model_area_m2! * CLEAR_HEIGHT * 1000) / 1000, r.layout_id!, 'True',
      glbRoomName(r.layout_id!, r.prototype_room_id!), 'estimated area of modeled polygon, not surveyed area',
    ].map(cell).join(','));
  });
}
writeFileSync(CSV, `${lines.join('\n')}\n`);

// ---- 3. building.json and tower-floors.ts
const generated = (level: string): boolean => /^T\d\d$/.test(level);
const kept = { levels: building.levels.filter((l) => !generated(l.id)), nodes: building.nodes.filter((n) => !generated(n.level)) };
const keptIds = new Set(kept.nodes.map((n) => n.id));
const tower = buildTower({ floors, rooms });
const first = tower.nodes[0];
for (const id of ['lobby', 'core-l10', 'plant']) if (!keptIds.has(id)) throw new Error(`slice node ${id} is missing`);
const join: Edge[] = first ? sliceJoin(first.id, first.level, Number(first.level.slice(1))) : [];
const out: Building = {
  ...building,
  levels: [...kept.levels, ...tower.levels],
  nodes: [...kept.nodes, ...tower.nodes],
  edges: [
    ...building.edges.filter((e) => keptIds.has(e.from) && keptIds.has(e.to) && !isGeneratedJoin(e.id)),
    ...join,
    ...tower.edges,
  ],
};
const items = (list: unknown[]): string => `[\n${list.map((i) => `    ${JSON.stringify(i)}`).join(',\n')}\n  ]`;
const sections = (['levels', 'nodes', 'edges', 'members', 'tokens'] as const).map((k) => `  "${k}": ${items(out[k])}`);
writeFileSync(BUILDING, `{\n  "note": ${JSON.stringify(out.note)},\n${sections.join(',\n')}\n}\n`);

const entries = Object.entries(assigned).map(([level, a]) => `  ${level}: { plan: '${a.plan}', turn: ${a.turn} },`);
writeFileSync(FLOORS_TS, `// Generated by data/whole-tower-build.ts (seed ${SEED}). Do not edit: rerun the script.
// Which typical floor plan each apartment level of 432 Park uses, and its turn in degrees.
import type { FloorPlan } from './tower-plans.ts';

export const TOWER_FLOORS: Record<string, FloorPlan> = {
${entries.join('\n')}
};
`);

const counts = Object.values(assigned).reduce<Record<string, number>>((m, a) => ({ ...m, [a.plan]: (m[a.plan] ?? 0) + 1 }), {});
console.log(`levels ${out.levels.length}, nodes ${out.nodes.length}, edges ${out.edges.length}; plans ${JSON.stringify(counts)}; csv rows ${lines.length - 1}`);
